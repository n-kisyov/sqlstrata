// Command drvbench compares Go SQLite drivers on workloads that matter for
// SQLStrata (scans, row streaming, keyset paging, anchor building, inserts).
//
// It lives in its own module so the benchmark-only dependencies (including the
// CGO driver) never leak into the application's go.mod.
//
//	go run . -db ../../testdata/big.db
//	CGO_ENABLED=1 go run -tags mattn . -db ../../testdata/big.db
package main

import (
	"database/sql"
	"flag"
	"fmt"
	"log"
	"math/rand/v2"
	"os"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"time"
)

// drivers is filled by the per-driver files via init().
var drivers = map[string]func(path string, ro bool) string{} // name -> DSN builder

func main() {
	dbPath := flag.String("db", "../../testdata/big.db", "database generated by cmd/gendb")
	only := flag.String("drivers", "", "comma separated subset of drivers to run")
	pages := flag.Int("pages", 2000, "random keyset pages to fetch")
	inserts := flag.Int("inserts", 1_000_000, "rows for the insert benchmark")
	flag.Parse()

	names := make([]string, 0, len(drivers))
	for n := range drivers {
		if *only == "" || slices.Contains(strings.Split(*only, ","), n) {
			names = append(names, n)
		}
	}
	slices.Sort(names)
	if len(names) == 0 {
		log.Fatal("no drivers selected")
	}

	fmt.Printf("%-10s %12s %12s %12s %12s %12s %10s\n", "driver", "agg-scan", "stream-rows", "keyset-page", "anchors", "insert", "heap-MB")
	for _, name := range names {
		r := run(name, drivers[name], *dbPath, *pages, *inserts)
		fmt.Printf("%-10s %12s %12s %12s %12s %12s %10.1f\n", name,
			r.agg.Round(time.Millisecond), r.stream.Round(time.Millisecond),
			r.page.Round(time.Microsecond), r.anchors.Round(time.Millisecond),
			r.insert.Round(time.Millisecond), r.heapMB)
	}
}

type result struct {
	agg, stream, page, anchors, insert time.Duration
	heapMB                             float64
}

func run(name string, dsn func(string, bool) string, path string, pages, inserts int) (r result) {
	sqlName := map[string]string{"ncruces": "sqlite3", "modernc": "sqlite", "mattn": "sqlite3mattn"}[name]
	db, err := sql.Open(sqlName, dsn(path, true))
	must(err)
	defer db.Close()
	db.SetMaxOpenConns(1)
	_, err = db.Exec(`PRAGMA cache_size=-32768`)
	must(err)

	var maxID int64
	must(db.QueryRow(`SELECT max(id) FROM orders`).Scan(&maxID))

	// 1. Aggregate scan: pure SQLite work, almost no driver crossings.
	t := time.Now()
	var n, sumLen int64
	must(db.QueryRow(`SELECT count(*), total(length(note)) FROM orders`).Scan(&n, new(float64)))
	r.agg = time.Since(t)

	// 2. Stream every row into Go values: driver overhead per row/column.
	t = time.Now()
	rows, err := db.Query(`SELECT id, customer_id, amount, status, created_at, note FROM orders`)
	must(err)
	var (
		id, cust      int64
		amount        float64
		status, ts    string
		note          sql.NullString
	)
	for rows.Next() {
		must(rows.Scan(&id, &cust, &amount, &status, &ts, &note))
		sumLen += int64(len(note.String))
	}
	must(rows.Err())
	r.stream = time.Since(t)

	// 3. Random keyset pages of 256 rows (what the grid does when scrolling).
	rng := rand.New(rand.NewPCG(7, 7))
	stmt, err := db.Prepare(`SELECT id, customer_id, amount, qty, status, created_at, substr(note,1,256), typeof(payload) FROM orders WHERE id > ? ORDER BY id LIMIT 256`)
	must(err)
	t = time.Now()
	for range pages {
		rows, err := stmt.Query(rng.Int64N(maxID))
		must(err)
		for rows.Next() {
			var a, b, q int64
			var amt float64
			var s, c, typ string
			var nt sql.NullString
			must(rows.Scan(&a, &b, &amt, &q, &s, &c, &nt, &typ))
		}
		must(rows.Close())
	}
	r.page = time.Since(t) / time.Duration(pages)
	stmt.Close()

	// 4. Sparse anchor index: every 1024th rowid.
	t = time.Now()
	rows, err = db.Query(`SELECT rowid FROM orders`)
	must(err)
	var anchors []int64
	for i := 0; rows.Next(); i++ {
		must(rows.Scan(&id))
		if i%1024 == 0 {
			anchors = append(anchors, id)
		}
	}
	must(rows.Err())
	r.anchors = time.Since(t)

	// 5. Bulk insert into a fresh temp database.
	tmp := filepath.Join(os.TempDir(), "drvbench-"+name+".db")
	for _, s := range []string{"", "-wal", "-shm", "-journal"} {
		os.Remove(tmp + s)
	}
	wdb, err := sql.Open(sqlName, dsn(tmp, false))
	must(err)
	wdb.SetMaxOpenConns(1)
	_, err = wdb.Exec(`PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL; CREATE TABLE t(id INTEGER PRIMARY KEY, a TEXT, b REAL, c INTEGER)`)
	must(err)
	t = time.Now()
	tx, err := wdb.Begin()
	must(err)
	ins, err := tx.Prepare(`INSERT INTO t VALUES (?,?,?,?)`)
	must(err)
	for i := range inserts {
		_, err = ins.Exec(i, "some text value for the row", float64(i)*1.5, i%97)
		must(err)
	}
	must(tx.Commit())
	r.insert = time.Since(t)
	wdb.Close()
	for _, s := range []string{"", "-wal", "-shm", "-journal"} {
		os.Remove(tmp + s)
	}

	var ms runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&ms)
	r.heapMB = float64(ms.HeapInuse) / (1 << 20)
	_ = sumLen
	return r
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}

